"""Производственный календарь РФ: праздники, перенесённые выходные, рабочие субботы.

Источник и пояснения — we_finance-analysts/requirements/reference/production-calendar-ru.md.
Меняется справочник — меняется и этот файл. Новый год добавляется, когда выходит
постановление Правительства о переносе выходных (обычно осенью предыдущего года).
"""

from datetime import date

# Нерабочие праздничные дни, ст. 112 ТК РФ: (месяц, день) → название.
FIXED_HOLIDAYS: dict[tuple[int, int], str] = {
    (1, 1): "Новогодние каникулы",
    (1, 2): "Новогодние каникулы",
    (1, 3): "Новогодние каникулы",
    (1, 4): "Новогодние каникулы",
    (1, 5): "Новогодние каникулы",
    (1, 6): "Новогодние каникулы",
    (1, 7): "Рождество Христово",
    (1, 8): "Новогодние каникулы",
    (2, 23): "День защитника Отечества",
    (3, 8): "Международный женский день",
    (5, 1): "Праздник Весны и Труда",
    (5, 9): "День Победы",
    (6, 12): "День России",
    (11, 4): "День народного единства",
}

# Годы, для которых есть постановление о переносе выходных.
CALENDAR_YEARS = frozenset({2025, 2026, 2027})

# Все праздники лет из CALENDAR_YEARS, включая выпавшие на субботу и воскресенье.
HOLIDAYS: dict[date, str] = {
    date(year, month, day): name
    for year in CALENDAR_YEARS
    for (month, day), name in FIXED_HOLIDAYS.items()
}

# Будние дни, ставшие выходными из-за переноса: дата → откуда перенесён.
TRANSFERRED_DAYS_OFF: dict[date, str] = {
    # 2025 — постановление Правительства РФ от 04.10.2024 № 1335
    date(2025, 5, 2): "с субботы 04.01.2025",
    date(2025, 5, 8): "с воскресенья 23.02.2025",
    date(2025, 6, 13): "с субботы 08.03.2025",
    date(2025, 11, 3): "с субботы 01.11.2025",
    date(2025, 12, 31): "с воскресенья 05.01.2025",
    # 2026 — постановление Правительства РФ от 24.09.2025 № 1466
    date(2026, 1, 9): "с субботы 03.01.2026",
    date(2026, 3, 9): "08.03.2026 — воскресенье (ст. 112 ТК РФ)",
    date(2026, 5, 11): "09.05.2026 — суббота (ст. 112 ТК РФ)",
    date(2026, 12, 31): "с воскресенья 04.01.2026",
    # 2027 — постановление Правительства РФ от 17.09.2026 № 1187
    date(2027, 2, 22): "с субботы 20.02.2027",
    date(2027, 5, 3): "01.05.2027 — суббота (ст. 112 ТК РФ)",
    date(2027, 5, 10): "09.05.2027 — воскресенье (ст. 112 ТК РФ)",
    date(2027, 6, 14): "12.06.2027 — суббота (ст. 112 ТК РФ)",
    date(2027, 11, 5): "с субботы 02.01.2027",
    date(2027, 12, 31): "с воскресенья 03.01.2027",
}

# Субботы, ставшие рабочими: дата → куда перенесён день отдыха.
WORKING_WEEKENDS: dict[date, str] = {
    date(2025, 11, 1): "на понедельник 03.11.2025",
    date(2027, 2, 20): "на понедельник 22.02.2027",
}


def is_business_day(day: date) -> bool:
    """Рабочий ли день по производственному календарю.

    Для лет без постановления — только выходные и постоянные праздники (без переносов).
    """
    if day in WORKING_WEEKENDS:
        return True
    if day.weekday() >= 5:
        return False
    if day.year in CALENDAR_YEARS:
        return day not in HOLIDAYS and day not in TRANSFERRED_DAYS_OFF
    return (day.month, day.day) not in FIXED_HOLIDAYS
